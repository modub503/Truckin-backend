/**
 * Prepares build/ for publishing.
 *
 * Two things happen here:
 *
 *   1. build/_headers is written — the single source of truth for Netlify
 *      response headers.
 *
 *      Why a build step instead of [[headers]] in netlify.toml: Netlify
 *      applies netlify.toml headers GLOBALLY — they cannot be scoped to a
 *      deploy context, so a top-level `X-Robots-Tag: noindex` would also
 *      apply to production. The supported way to vary headers per deploy is
 *      a `_headers` file in the publish directory, which is regenerated on
 *      every build.
 *
 *      The dispatch app is an employee-only tool behind auth. It is never
 *      indexed, in any deploy context, so the robots tag is `noindex,
 *      nofollow` throughout.
 *
 *   2. netlify.toml and .netlifyignore are copied into build/.
 *
 *      That makes the build folder self-contained: dropping build/ into
 *      Netlify by hand still gets the SPA fallback, the /api/* proxy to
 *      Render and the blocked paths, because Netlify reads the deploy
 *      config from the root of the folder it publishes.
 *
 * Run with: npm run publish
 */

import { writeFileSync, copyFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const projectDir = resolve(here, "..");
const publishDir = resolve(projectDir, "build");

if (!existsSync(publishDir)) {
	console.error("[publish] build/ not found — run the build first.");
	process.exit(1);
}

const context = process.env.CONTEXT ?? "dev";
const robotsTag =
	process.env.ROBOTS_TAG ??
	(context === "production" ? "noindex, nofollow" : "noindex, nofollow");

const body = [
	"# Generated by scripts/prepare-publish.mjs — do not edit by hand.",
	`# Deploy context: ${context}`,
	"",
	"# Fingerprinted build assets never change.",
	"/static/*",
	"  Cache-Control: public, max-age=31536000, immutable",
	"",
	"# Every response: security headers + never index this app.",
	"/*",
	"  X-Content-Type-Options: nosniff",
	"  Referrer-Policy: strict-origin-when-cross-origin",
	"  X-Frame-Options: SAMEORIGIN",
	`  X-Robots-Tag: ${robotsTag}`,
	"",
	"# The app shell must not be cached, or a deploy would not reach the browser.",
	"/index.html",
	"  Cache-Control: no-cache, must-revalidate",
	"",
].join("\n");

writeFileSync(resolve(publishDir, "_headers"), body, "utf8");
console.log(`[publish] build/_headers written — X-Robots-Tag: ${robotsTag} (context: ${context})`);

// Make the build folder self-contained, so a hand-dropped build/ keeps the
// redirects and the /api/* proxy.
copyFileSync(resolve(projectDir, "netlify.toml"), resolve(publishDir, "netlify.toml"));
copyFileSync(resolve(projectDir, ".netlifyignore"), resolve(publishDir, ".netlifyignore"));
console.log("[publish] build/netlify.toml and build/.netlifyignore copied");
